# 8교시-1
# 점수 전처리 코드 수정: 잘못된 행을 건너뛰고 정상 점수만 정규화하기
#
# 입력 예: [{"score": 85}, {"score": "N/A"}, {"score": 100}]
# 반환 예: [0.85, 1.0]
# 처리 기준: 0점 이상 100점 이하인 점수만 100으로 나누고 소수 넷째 자리까지 반올림합니다.
# 잘못된 행은 안내문을 출력하고 제외합니다. 제외한 행의 자리를 0으로 채우지는 않습니다.
#
# 아래에서 [유지]는 원래 코드의 기능을 그대로 둔 부분,d
# [변경]은 기존 코드를 바꾼 부분, [추가]는 원본에 없던 부분입니다.


# 수정 전 원본: 비교를 위한 주석이므로 실행되지 않습니다.
# def preprocess_legacy(data):
#     res = []
#     for row in data:
#         score = float(row["score"])
#         res.append(round(score / 100.0, 4))
#     return res
#
# 원본의 문제:
# 1. score 키가 없는 행에서는 KeyError가 발생해 함수 실행이 중단됩니다.
# 2. "N/A"를 float로 변환하면 ValueError가 발생해 함수 실행이 중단됩니다.
# 3. 범위 검사가 없어 120점도 1.2로 변환됩니다. 음수 점수도 그대로 처리됩니다.


def preprocess_legacy(data):  # [유지] 기존 함수 이름을 유지하여 같은 방식으로 호출할 수 있게 했습니다.
    res = []  # [유지] 정상 점수의 정규화 결과를 차례대로 담을 빈 리스트입니다.

    for row_number, row in enumerate(data, start=1):  # [변경] 이전: for row in data: → 오류가 난 행을 알 수 있도록 1부터 번호를 붙였습니다.
        try:  # [추가] 이전에는 바로 변환했습니다. 이제 예외를 처리하여 한 행의 오류 때문에 전체 작업이 중단되지 않게 합니다.
            score = float(row["score"])  # [이동] 이전과 같은 변환 코드를 try 안으로 옮겼습니다. "85" 같은 숫자 문자열도 처리합니다.
        except KeyError:  # [추가] 이전에는 score 키 누락 시 중단되었습니다. 누락된 키 오류만 따로 처리합니다.
            print(f"[{row_number}행 제외] 'score' 키가 없습니다.")  # [추가] 어떤 행이 왜 제외되었는지 알려 줍니다.
            continue  # [추가] 이 행의 처리를 끝내고 다음 행으로 넘어갑니다. 잘못된 값을 결과에 넣지 않습니다.
        except (TypeError, ValueError, OverflowError):  # [추가] "N/A", None, 잘못된 행 형식, float로 바꾸기에는 너무 큰 정수 등을 처리합니다.
            print(f"[{row_number}행 제외] 점수를 숫자로 변환할 수 없습니다: {row!r}")  # [추가] !r은 원본 값을 따옴표 등과 함께 표시하여 확인하기 쉽게 합니다.
            continue  # [추가] 변환 실패 후에는 아래의 비교나 나눗셈을 실행하지 않고 다음 행을 처리합니다.

        if not (0.0 <= score <= 100.0):  # [추가] 이전에는 범위 검사가 없었습니다. 0~100 밖의 점수와 NaN, 무한대를 제외합니다.
            print(f"[{row_number}행 제외] 점수는 0~100의 유한한 숫자여야 합니다: {score}")  # [추가] 120점 등을 정상 점수처럼 처리하지 않고 제외 이유를 출력합니다.
            continue  # [추가] 범위를 벗어난 값을 정규화하지 않도록 다음 행으로 넘어갑니다.

        res.append(round(score / 100.0, 4))  # [유지·위치 변경] 계산식은 그대로 두되, 변환과 범위 검사에 모두 통과한 점수만 추가합니다.

    return res  # [유지] 반복이 모두 끝나면 정상 점수만 담긴 리스트를 반환합니다.


# 수정한 문법을 짧게 풀어 봅시다.
#
# enumerate(data, start=1): 각 행에 1, 2, 3, ... 번호를 붙입니다.
# try / except: 문제가 생길 수 있는 작업을 시도하고, 지정한 예외가 생기면 대응합니다.
# continue: 현재 반복의 남은 코드를 건너뛰고 다음 행을 처리합니다.
# 0.0 <= score <= 100.0: 점수가 0 이상이면서 동시에 100 이하인지 검사합니다.
# not: 참과 거짓을 뒤집으므로, 여기서는 허용 범위에 들어가지 않는 점수를 찾습니다.
# NaN은 숫자로 비교할 수 없는 특수한 값입니다. 위 범위 조건이 거짓이 되어 제외됩니다.
# round(score / 100.0, 4): 점수를 0~1 범위로 바꾸고 소수 넷째 자리까지 반올림합니다.
# append: 리스트 맨 뒤에 항목 하나를 추가합니다.
#
# 중요한 차이:
# .get("score", 0)으로 누락된 점수를 0점으로 바꾸지 않았습니다.
# 실제 0점과 누락된 점수는 다르므로, 누락된 행은 제외하고 실제 0점은 보존합니다.


if __name__ == "__main__":  # [추가] 이 파일을 직접 실행할 때만 아래 예시를 실행합니다. 다른 파일에서 가져올 때는 실행하지 않습니다.
    sample_data = [  # [추가] 수정 전 문제와 수정 후 동작을 확인할 예시 데이터입니다.
        {"score": 85},  # 정상 숫자: 0.85로 변환됩니다.
        {},  # 키 누락: KeyError를 처리하고 다음 행으로 넘어갑니다.
        {"score": "N/A"},  # 숫자가 아닌 문자열: ValueError를 처리하고 다음 행으로 넘어갑니다.
        {"score": 120},  # 범위 초과: 원본의 잘못된 결과 1.2를 만들지 않고 제외합니다.
        {"score": -5},  # 음수 점수: 허용 범위 밖이므로 제외합니다.
        {"score": None},  # 빈 값: TypeError를 처리하고 다음 행으로 넘어갑니다.
        {"score": "NaN"},  # float 변환은 되지만 정상 점수가 아니므로 범위 검사에서 제외합니다.
        {"score": "90.12345"},  # 정상 숫자 문자열: 0.9012로 변환됩니다. 오류 뒤의 정상 행도 처리됩니다.
        {"score": 0},  # 최솟값도 정상 점수입니다. 0.0으로 변환됩니다.
        {"score": 100},  # 최댓값도 정상 점수입니다. 1.0으로 변환됩니다.
    ]
    result = preprocess_legacy(sample_data)  # [추가] 수정한 함수로 예시 데이터를 끝까지 처리합니다.
    print(f"정규화 결과: {result}")  # [추가] 정상 점수만 모인 결과를 화면에 출력합니다.


